package com.qust.helper.data

/**
 * 【本期】"这次是从哪个入口打开登录页的"标记。
 *
 * 目前只有一处需要区分: **从「账号管理 → 教务系统」点"点击登录"**时,
 * 用户只是想单独确认一下教务能不能进, 不希望顺手把数字青科的账号密码存下来,
 * 也不希望后台自动去拉一遍课表(会把本地调休/调课改动覆盖掉)。
 *
 * 登录页是导航栈里的一个页面(没有 arguments), 用一个短生命周期的标记传递最省事:
 * 账号管理在跳转前置位, 教务登录页在离开(`onDispose`)时复位。
 */
object LoginEntry {

	/** 教务登录页是否由「账号管理 → 教务系统 → 点击登录」打开 */
	var fromAccountManager: Boolean = false

	/**
	 * 【第八十九轮·按要求】小组件页「登录后添加」的接力标志:
	 * 点按钮时置位并直接进饮水码登录页(不再弹"请先登录饮水账号"气泡),
	 * 登录成功后由 DrinkLoginPage 自动把饮水码小组件钉到桌面, 然后复位。
	 */
	var autoAddDrinkWidget: Boolean = false

	/**
	 * 【第四十轮·按要求】「教务登陆」页是否由**欢迎页(刚进入软件)**打开的
	 * (`finishOnLogin` 标记)。只有这条路径登录成功后才允许自动查课表,
	 * 其余入口(账号管理 / 教务网页 / 选课网页)登录完一律不动课表。
	 *
	 * 教务登录页在组合时按 Intent 的 `finishOnLogin` 置位, 离开(`onDispose`)时复位。
	 */
	var fromAppEntry: Boolean = false

	/**
	 * 【本轮·新增】「教务登陆」页是否由「数字青科登陆」页**接着**打开的。
	 *
	 * 登录链路是: 未登录 → 先「数字青科登陆」→ 教务管理系统进不去 → 再「教务登陆」。
	 * 这时如果「教务登陆」页又因为"两个输入框都留空"把人送回「数字青科登陆」,
	 * 两个页面就会来回弹。用这个标记阻断回跳, 离开「教务登陆」时复位。
	 */
	var fromVpnLogin: Boolean = false

	/**
	 * 【本轮·新增】这次打开「数字青科登陆」是**被功能页面拉来的**(学业/成绩/考试/通知/课表查询/教务网页/选课网页),
	 * 而不是用户自己在「账号管理」里点"登录"。
	 *
	 * 只有前者才需要在"数字青科登上了、但教务管理系统进不去"时, 自动接着弹「教务登陆」;
	 * 后者用户就是来管理账号的, 登完就该停在这一页 —— 以前不加区分, 于是
	 * "在账号管理里登录数字青科, 紧接着蹦出教务系统的登录界面"。
	 *
	 * 由 `AppWidgets.CheckEasLogin` 在跳转前置位, 「数字青科登陆」页离开时复位。
	 */
	var autoFallbackToEas: Boolean = false

	/**
	 * 【第三十一轮】"登录完要去哪一页"。
	 *
	 * 「数字青科」栏目的 3 个功能(数字青科 / 智慧体测 / 座位预约)在**没登录统一身份时
	 * 会在导航那一刻直接改道到登录页**(见 `Page.resolve`) —— 一次转场, 不再"先开页面、
	 * WebView 检查一圈、再弹出登录页", 也就是用户说的"卡顿 / 有时候不显示"。
	 *
	 * 代价是原来的"功能页"没被压进回退栈, 所以把目标页记在这里: 登录成功后
	 * `popUpTo` 掉登录页、直接跳到用户本来想去的那个功能页。
	 */
	var pendingVpnPage: String? = null

	/**
	 * 【第三十三轮·按要求】「学校邮箱登陆」页是否由「账号管理 → 学校邮箱」的"点击登录/更换账号"打开。
	 *
	 * 用户原话: "在该页面点击登录学校邮箱时, 不要进入学校邮箱网页, 保存好账号和密码后直接退出就行,
	 * 点击『其他』里面的『学校邮箱』时才进入学校邮箱页面。"
	 *
	 * 从账号管理进来时, 登录成功只**保存账号密码 + 退回账号管理**;
	 * 只有从「其他 → 学校邮箱」这个功能页进来的, 保存后才回到邮箱网页由 WebView 自动登录。
	 * 由账号管理在跳转前置位, 「学校邮箱登陆」页离开时复位。
	 */
	var mailFromAccountManager: Boolean = false

}
